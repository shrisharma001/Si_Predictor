"""build_paper_numbers.py - writes paper/paper_numbers.md: every number the paper may quote, with its source file.
Run after all experiments:  python build_paper_numbers.py"""
import os
import pandas as pd

R = "results/"
os.makedirs("paper", exist_ok=True)

PRODUCER = {"data_facts.csv": "export_data_facts.py", "cleaner_report.csv": "export_data_facts.py", "consolidated_results.csv": "consolidate.py",
            "cv_summary.csv": "run_experiments.py --stage cv", "bootstrap_tests.csv": "run_extra.py --stage analysis",
            "error_by_regime.csv": "run_extra.py --stage analysis", "split_comparison.csv": "run_split_comparison.py",
            "cv_history_summary.csv": "run_extra.py --stage history", "intervals_cv_summary.csv": "run_uncertainty.py",
            "intervals_test_results.csv": "run_uncertainty.py", "learning_curve_summary.csv": "run_learning_curve.py",
            "cv_band_summary.csv": "run_extra.py --stage classify", "test_band_results.csv": "run_extra.py --stage classify",
            "sensitivity_cv_summary.csv": "run_sensitivity.py", "domain_cv_summary.csv": "run_domain.py", "thermal_cv_summary.csv": "run_thermal.py",
            "ideas_cv_summary.csv": "run_ideas.py", "ideas2_cv_summary.csv": "run_ideas2.py"}
MISSING = []


def rd(name):
    """Read a results CSV; if it is missing, remember which script creates it and continue with an empty table."""
    try:
        return pd.read_csv(R + name)
    except FileNotFoundError:
        MISSING.append(name)
        return pd.DataFrame({"missing": [f"run {PRODUCER.get(name, 'the script that creates it')} first"]})

def md(df, floatfmt=3):
    df = df.copy()
    cols = [str(c) for c in df.columns]
    out = ["| " + " | ".join(cols) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, r in df.iterrows():
        cells = []
        for v in r.values:
            cells.append("" if (isinstance(v, float) and v != v) else (f"{v:.{floatfmt}f}" if isinstance(v, float) else str(v)))
        out.append("| " + " | ".join(cells) + " |")
    return "\n".join(out)

def section(title, source, body, note=""):
    s = f"\n## {title}\n*Source: `{source}`*\n\n{body}\n"
    return s + (f"\n{note}\n" if note else "")

parts = ["# Numbers for the paper (generated by build_paper_numbers.py - do not edit by hand)\n",
         "Every figure below is read from a file in `results/`. If a number in the paper is not here, it is not sourced."]

f = rd("data_facts.csv"); parts.append(section("Dataset and protocol facts", "results/data_facts.csv", md(f)))
c = rd("cleaner_report.csv"); parts.append(section("Sensor faults found by the cleaner (development period)", "results/cleaner_report.csv", md(c)))
T0 = rd("consolidated_results.csv"); t = T0
parts.append(section("Main comparison (CV mean over 5 folds, and one-shot test)", "results/consolidated_results.csv", md(t, 4),
    "CV_MAE_std is the standard deviation across the 5 folds. GRU row = mean of 5 independent runs x 3 seeds (user's machine)."))
cv = rd("cv_summary.csv")
parts.append(section("CV summary for all feature sets and models", "results/cv_summary.csv", md(cv, 4), "F0 = raw sensors, F1 = +lags, F2 = +rolling, F3 = both; +H = previous Si results added."))
b = rd("bootstrap_tests.csv"); parts.append(section("Paired block-bootstrap tests on test-set absolute error (negative = A better)", "results/bootstrap_tests.csv", md(b, 4)))
e = rd("error_by_regime.csv"); parts.append(section("Test MAE by true-Si regime", "results/error_by_regime.csv", md(e, 4)))
s = rd("split_comparison.csv"); parts.append(section("Effect of the split method (development period only)", "results/split_comparison.csv", md(s, 4)))
h = rd("cv_history_summary.csv"); parts.append(section("History length sweep and MLP baseline (CV)", "results/cv_history_summary.csv", md(h, 4)))
for name, title in [("intervals_cv_summary.csv", "Prediction intervals, CV (nominal 90 %)"), ("intervals_test_results.csv", "Prediction intervals, test (nominal 90 %)")]:
    d = pd.read_csv(R + name); parts.append(section(title, "results/" + name, md(d, 3)))
l = rd("learning_curve_summary.csv"); parts.append(section("Learning curve (CV folds 3-5, most recent N training samples)", "results/learning_curve_summary.csv", md(l, 4), "The 10,000-sample point uses only 2 folds."))
bs = rd("cv_band_summary.csv"); bt = rd("test_band_results.csv")
parts.append(section("Si-band classification (secondary)", "results/cv_band_summary.csv, results/test_band_results.csv", md(bs.reset_index(), 3) + "\n\nTest:\n\n" + md(bt, 3)))
sens = rd("sensitivity_cv_summary.csv"); parts.append(section("Hyperparameter sensitivity of the hybrid (one at a time, CV)", "results/sensitivity_cv_summary.csv", md(sens, 4)))
neg = []
for name, title in [("domain_cv_summary.csv", "Domain features"), ("thermal_cv_summary.csv", "Hot-blast (Th) thermal features"), ("ideas_cv_summary.csv", "State-change, delta-target, slow features"), ("ideas2_cv_summary.csv", "Sliding window, error feedback, blend")]:
    d = pd.read_csv(R + name); keep = [c for c in d.columns if c in ("variant", "MAE_mean", "MAE_std", "R2_mean", "R2_normal_mean", "within_0.10_mean")]
    neg.append(f"**{title}** (`results/{name}`)\n\n" + md(d[keep] if keep else d, 4))
parts.append("\n## Negative results (all CV only)\n\n" + "\n\n".join(neg) + "\n")
open("paper/paper_numbers.md", "w").write("\n".join(parts))
print("wrote paper/paper_numbers.md,", sum(len(p) for p in parts), "characters")

if MISSING:
    print("\nWARNING: paper/paper_numbers.md is INCOMPLETE. Missing result files and the script that creates each:")
    for m in MISSING:
        print(f"  {m:32s} <- python {PRODUCER.get(m, '?')}")